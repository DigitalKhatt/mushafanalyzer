#!/usr/bin/env python3
"""Fit skeleton-template positions and tolerances from reviewed PAW cuts.

The review file is deliberately separate from a segmenter's own confidence:
accepted/confident output is not ground truth. Its format is:

  {
    "examples": [
      {"wordId": "l00_w02", "pawIndex": 0,
       "status": "accepted", "cuts": [1283.49, 2267.65]}
    ]
  }

`cuts` are spine arclengths in transcription order. Only records whose status
is `accepted` are used. The input summary must have been generated by
segment_paw_letters.py after skeletonEvents were added.
"""

from __future__ import annotations

import argparse
import json
from dataclasses import replace
from typing import Dict, List, Sequence, Tuple

import numpy as np

from segment_paw_letters import (
    DEFAULT_TEMPLATE_PATH,
    SkeletonTemplate,
    elastic_body_template_to_json,
    elastic_body_templates_from_json,
    skeleton_template_to_json,
    skeleton_templates_from_json,
)


def _review_index(payload: dict) -> Dict[Tuple[str, int], dict]:
  examples = payload.get("examples", [])
  return {(str(record["wordId"]), int(record["pawIndex"])): record
          for record in examples if record.get("status") == "accepted"}


def _paws(summaries: Sequence[str]):
  for path in summaries:
    with open(path, encoding="utf-8") as fh:
      words = json.load(fh)
    for word in words:
      for paw in word.get("paws", []):
        yield word["wordId"], paw


def _applies(template: SkeletonTemplate, letters: Sequence[str],
             forms: Sequence[str], start: int) -> bool:
  end = start + len(template.letters)
  if (end > len(letters)
      or any(actual not in allowed
             for allowed, actual in zip(template.letters,
                                        letters[start:end]))):
    return False
  return all(want == "*" or want == actual
             for want, actual in zip(template.forms, forms[start:end]))


def _align_steps(template: SkeletonTemplate, events: Sequence[dict],
                 a_s: float, b_s: float):
  span = b_s - a_s
  if span <= 1e-6:
    return None
  local = [(idx, event, (float(event["s"]) - a_s) / span)
           for idx, event in enumerate(events) if a_s < float(event["s"]) < b_s]
  aligned = []
  last = -1
  for step in template.steps:
    choices = [(abs(pos - step.target), j, event, pos)
               for j, (_, event, pos) in enumerate(local)
               if j > last and event.get("kind") == step.kind]
    if not choices:
      if step.optional:
        aligned.append(None)
        continue
      return None
    _, last, event, pos = min(choices)
    aligned.append((float(pos), float(event.get("strength", 0.0))))
  return aligned


def fit_templates(summaries: Sequence[str], reviews: dict,
                  templates: Sequence[SkeletonTemplate], min_samples: int
                  ) -> Tuple[List[SkeletonTemplate], dict]:
  reviewed = _review_index(reviews)
  observations: Dict[str, List[List[Tuple[float, float] | None]]] = {
      template.name: [] for template in templates}
  used_examples = 0
  for word_id, paw in _paws(summaries):
    key = (word_id, int(paw["pawIndex"]))
    review = reviewed.get(key)
    if review is None:
      continue
    letters, forms = paw.get("letters", []), paw.get("forms", [])
    cuts = [float(value) for value in review.get("cuts", [])]
    if len(cuts) != max(0, len(letters) - 1):
      continue
    bounds = [0.0] + cuts + [float(paw["spineLength"])]
    events = paw.get("skeletonEvents", [])
    used_examples += 1
    for template in templates:
      consume = len(template.letters)
      for start in range(0, len(letters) - consume + 1):
        if not _applies(template, letters, forms, start):
          continue
        aligned = _align_steps(
            template, events, bounds[start], bounds[start + consume])
        if aligned is not None:
          observations[template.name].append(aligned)

  fitted: List[SkeletonTemplate] = []
  counts = {}
  for template in templates:
    rows = observations[template.name]
    counts[template.name] = len(rows)
    if len(rows) < min_samples:
      fitted.append(template)
      continue
    steps = []
    for step_index, step in enumerate(template.steps):
      values = [row[step_index] for row in rows if row[step_index] is not None]
      if len(values) < min_samples:
        steps.append(step)
        continue
      positions = np.asarray([value[0] for value in values], dtype=float)
      strengths = np.asarray([value[1] for value in values], dtype=float)
      median = float(np.median(positions))
      mad = float(np.median(np.abs(positions - median)))
      steps.append(replace(
          step, target=median, tolerance=max(0.10, 2.5 * 1.4826 * mad),
          min_strength=max(0.0, float(np.quantile(strengths, 0.10)))))
    fitted.append(replace(template, steps=tuple(steps)))
  return fitted, {"reviewedExamples": used_examples, "samples": counts}


def main() -> int:
  ap = argparse.ArgumentParser(description=__doc__)
  ap.add_argument("--summary", action="append", required=True,
                  help="page_summary.json with skeletonEvents; repeatable")
  ap.add_argument("--reviews", required=True,
                  help="reviewed cut annotations in the format above")
  ap.add_argument("--templates", default=DEFAULT_TEMPLATE_PATH,
                  help="starting template JSON (defaults to runtime document)")
  ap.add_argument("--min-samples", type=int, default=3)
  ap.add_argument("--out", required=True)
  args = ap.parse_args()

  with open(args.reviews, encoding="utf-8") as fh:
    reviews = json.load(fh)
  with open(args.templates, encoding="utf-8") as fh:
    template_payload = json.load(fh)
  templates = skeleton_templates_from_json(template_payload)
  elastic_templates = elastic_body_templates_from_json(template_payload)
  fitted, metadata = fit_templates(
      args.summary, reviews, templates, args.min_samples)
  payload = {"version": 1, **metadata,
             "templates": [skeleton_template_to_json(t) for t in fitted],
             "elasticBodyTemplates": [
                 elastic_body_template_to_json(t) for t in elastic_templates]}
  with open(args.out, "w", encoding="utf-8") as fh:
    json.dump(payload, fh, ensure_ascii=False, indent=2)
  print(json.dumps(metadata, ensure_ascii=False))
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
